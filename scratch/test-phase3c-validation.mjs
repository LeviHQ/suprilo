// 2. Service Worker URL Sanitization & Same-Origin Enforcement
// ---------------------------------------------------------------------------
{
  const ALLOWED_EXACT_ROUTES = [
    "/profile",
    "/profile/badges",
    "/profile/notifications",
    "/profile/settings",
    "/profile/analytics",
    "/templates",
    "/create",
  ];

  const ALLOWED_PARAM_PREFIXES = ["/c/", "/b/"];

  const isSafeInternalPath = (pathname) => {
    if (ALLOWED_EXACT_ROUTES.includes(pathname)) return true;
    for (const prefix of ALLOWED_PARAM_PREFIXES) {
      if (pathname.startsWith(prefix)) {
        const param = pathname.slice(prefix.length);
        if (/^[a-zA-Z0-9_-]{1,64}$/.test(param)) return true;
      }
    }
    return false;
  };

  const sanitizeTargetUrl = (rawUrl, origin = "https://suprilo.com") => {
    if (typeof rawUrl !== "string" || !rawUrl.trim()) return `${origin}/profile`;
    const trimmed = rawUrl.trim();
    if (
      trimmed.startsWith("//") ||
      trimmed.toLowerCase().startsWith("javascript:") ||
      trimmed.toLowerCase().startsWith("data:")
    ) {
      return `${origin}/profile`;
    }
    try {
      const parsed = new URL(trimmed, origin);
      if (parsed.origin !== origin) return `${origin}/profile`;
      if (isSafeInternalPath(parsed.pathname)) {
        return `${origin}${parsed.pathname}`;
      }
    } catch {}
    return `${origin}/profile`;
  };

  // Legitimate destinations generated by API
  assert(sanitizeTargetUrl("/c/my-scratch-card") === "https://suprilo.com/c/my-scratch-card",
    "Test 2a: Valid card slug destination /c/:slug permitted");
  assert(sanitizeTargetUrl("/c/a1b2c3d4-e5f6-4a7b-8c9d-0e1f2a3b4c5d") === "https://suprilo.com/c/a1b2c3d4-e5f6-4a7b-8c9d-0e1f2a3b4c5d",
    "Test 2b: Valid card UUID destination permitted");
  assert(sanitizeTargetUrl("/b/speedy-scratcher") === "https://suprilo.com/b/speedy-scratcher",
    "Test 2c: Valid badge identifier destination /b/:id permitted");
  assert(sanitizeTargetUrl("/profile") === "https://suprilo.com/profile",
    "Test 2d: /profile destination permitted");
  assert(sanitizeTargetUrl("/profile/badges") === "https://suprilo.com/profile/badges",
    "Test 2e: /profile/badges destination permitted");
  assert(sanitizeTargetUrl("/profile/notifications") === "https://suprilo.com/profile/notifications",
    "Test 2f: /profile/notifications destination permitted");
  assert(sanitizeTargetUrl("/profile/settings") === "https://suprilo.com/profile/settings",
    "Test 2g: /profile/settings destination permitted");
  assert(sanitizeTargetUrl("/profile/analytics") === "https://suprilo.com/profile/analytics",
    "Test 2h: /profile/analytics destination permitted");
  assert(sanitizeTargetUrl("/templates") === "https://suprilo.com/templates",
    "Test 2i: /templates destination permitted");
  assert(sanitizeTargetUrl("/create") === "https://suprilo.com/create",
    "Test 2j: /create destination permitted");

  // Unsafe, spoofed, or cross-origin URLs (strictly neutralized)
  assert(sanitizeTargetUrl("/profile-evil") === "https://suprilo.com/profile",
    "Test 2k: Prefix spoofing /profile-evil neutralized to /profile");
  assert(sanitizeTargetUrl("/create-fake") === "https://suprilo.com/profile",
    "Test 2l: Prefix spoofing /create-fake neutralized to /profile");
  assert(sanitizeTargetUrl("/c/invalid;injection") === "https://suprilo.com/profile",
    "Test 2m: Parameter with semicolon injection neutralized to /profile");
  assert(sanitizeTargetUrl("/c/slug/../../admin") === "https://suprilo.com/profile",
    "Test 2n: Directory traversal path neutralized to /profile");
  assert(sanitizeTargetUrl("https://evil-phish.com/login") === "https://suprilo.com/profile",
    "Test 2o: External cross-origin URL neutralized to /profile");
  assert(sanitizeTargetUrl("//evil.com/payload") === "https://suprilo.com/profile",
    "Test 2p: Protocol-relative URL neutralized to /profile");
  assert(sanitizeTargetUrl("javascript:alert(document.cookie)") === "https://suprilo.com/profile",
    "Test 2q: Javascript pseudo-protocol neutralized to /profile");
  assert(sanitizeTargetUrl("data:text/html,<script>alert(1)</script>") === "https://suprilo.com/profile",
    "Test 2r: Data URI neutralized to /profile");
  assert(sanitizeTargetUrl("") === "https://suprilo.com/profile",
    "Test 2s: Empty string defaults safely to /profile");
  assert(sanitizeTargetUrl(null) === "https://suprilo.com/profile",
    "Test 2t: Null value defaults safely to /profile");
}

