/**
 * Deterministic pseudo-random seed generator for curated general feed
 */
function seededShuffle<T>(array: T[], seed: number): T[] {
  const result = [...array];
  let m = result.length;
  let t: T;
  let i: number;
  let s = seed;

  while (m) {
    s = (s * 9301 + 49297) % 233280;
    i = Math.floor((s / 233280) * m--);
    t = result[m];
    result[m] = result[i];
    result[i] = t;
  }
  return result;
}

/**
 * Returns balanced, curated templates for the General Showcase.
 * Shuffles across all 10 categories to ensure diverse visual styles and foils.
 */
export function getCuratedGeneralTemplates(seed = 42): TemplateDefinition[] {
  return seededShuffle(SU_PRILO_TEMPLATES, seed);
}

/**
 * Filter templates by category
 */
export function getTemplatesByCategory(
  category?: TemplateCategory | "all"
): TemplateDefinition[] {
  if (!category || category === "general" || category === "all") {
    return getCuratedGeneralTemplates();
  }
  return SU_PRILO_TEMPLATES.filter((t) => t.category === category);
}

export function getTemplateById(id: string): TemplateDefinition | undefined {
  return SU_PRILO_TEMPLATES.find((t) => t.id === id);
}

